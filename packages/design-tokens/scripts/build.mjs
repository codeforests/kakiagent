// Builds dist/tokens.css (dashboard and operator, light only per UX-Q1) and
// dist/widget-tokens.js (the --kaki-* bundle, light and dark, ADR-016) from
// docs/02-design/tokens.json, the only source of design values. Exits 1 if any
// colour pair drops below its WCAG AA minimum.
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { contrastReport, declarations, loadTokens } from './tokens.mjs';

const TOKENS = fileURLToPath(new URL('../../../docs/02-design/tokens.json', import.meta.url));
const DIST = fileURLToPath(new URL('../dist/', import.meta.url));

const flat = loadTokens(TOKENS);
const failures = contrastReport(flat).filter((r) => !r.ok);
if (failures.length) {
  for (const f of failures) {
    console.error(`contrast FAIL (${f.mode}) ${f.fg} on ${f.bg}: ${f.ratio.toFixed(2)} < ${f.min}`);
  }
  process.exit(1);
}

const light = declarations(flat, 'light');
const dark = declarations(flat, 'dark');
const block = (decls) => decls.map(([n, v]) => `  ${n}: ${v};`).join('\n');
const header =
  '/* GENERATED by @kaki/design-tokens from docs/02-design/tokens.json. Do not edit. */\n';

mkdirSync(DIST, { recursive: true });
writeFileSync(`${DIST}tokens.css`, `${header}:root {\n${block(light.core)}\n}\n`);

const widgetDecl = (decls) => decls.map(([n, v]) => `${n}:${v}`).join(';');
writeFileSync(
  `${DIST}widget-tokens.js`,
  `${header}export const widgetTokens = ${JSON.stringify({ light: widgetDecl(light.widget), dark: widgetDecl(dark.widget) })};\n`,
);
writeFileSync(
  `${DIST}widget-tokens.d.ts`,
  `${header}/** \`--kaki-*\` declarations for the widget's shadow host, per scheme. */\nexport declare const widgetTokens: { light: string; dark: string };\n`,
);
console.log(
  `design-tokens: ${light.core.length} core and ${light.widget.length} widget variables; contrast ok`,
);
